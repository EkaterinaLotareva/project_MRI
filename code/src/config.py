import numpy as np

# Геометрия системы
m = 6                      # Количество стопок
n = 5                      # Количество колец в стопке
radii = np.array([
        0.049914577521006184,
        0.04978850900183142,
        0.02460963888465753,
        0.028878823305504828,
        0.04991655719139329
    ])   # большие
gaps  = np.array([
        0.005705957411018678,
        0.03833215032718407,
        0.030265734841392257,
        0.008726365695000763
    ])  

N_seg = 1024                # Дискретизация кольца


# Физические параметры
r_ohm = 0.7            # Активное сопротивление кольца
U_0 = 200                  # Амплитуда напряжения
A = 0.3                   # Расстояние от центра до первой стопки
R_domain = 0.5*A 
phi_0 = 0                  # Начальная фаза
frequency_MHz = 300       # Частота в МГц
omega = 2 * np.pi * frequency_MHz * 1e6
L_self = 1.5e-7            # Собственная индуктивность кольца
C = np.full(n*m, 1.68e-12)  # Емкость колец (Фарады)
# C = np.full(n*m, 1.95239801e-11)  # Емкость колец

def get_fixed_params():
    return {
        'n': n, 'm': m, 'R': radii, 'delta': gaps, 'N': N_seg,
        'r_ohm': r_ohm, 'L_own': L_self, 'U_0': U_0, 'A': A, 'phi': phi_0,
        'omega': omega, 'R_domain': R_domain,
        'C': C,
    }